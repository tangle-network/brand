#!/usr/bin/env node
// Generates src/palette.generated.ts: Brand's resolved colors for renderers that
// cannot read CSS variables (PDF, canvas, WebGL, email, the theme-color meta).
// Values are read from tokens.css and named-themes.css; run with --check in build.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { block, decls, resolveHex, resolveValue } from "./css-resolve.mjs";

const here = path.dirname(new URL(import.meta.url).pathname);
const styles = path.join(here, "..", "src", "styles");
const OUT = path.join(here, "..", "src", "palette.generated.ts");
const tokens = readFileSync(path.join(styles, "tokens.css"), "utf8");
const named = readFileSync(path.join(styles, "named-themes.css"), "utf8");

const DARK = decls(block(tokens, ".dark"));
const LIGHT = { ...DARK, ...decls(block(tokens, "\n.light")) };
const WEBSITE_LIGHT = { ...LIGHT, ...decls(block(named, '[data-theme="website"]:where(:not(.dark))')) };
const WEBSITE_DARK = { ...DARK, ...decls(block(named, '.dark[data-theme="website"]')) };
const resolve = (scope, name) => {
  const v = resolveValue(scope, name);
  return /^rgba?\(/.test(v) ? v : resolveHex(scope, name);
};
// Role name -> token. Planes, ink, accent, status surfaces and the indigo ramp.
const ROLES = {
  canvas: "md3-surface", card: "md3-surface-container", well: "md3-surface-container-low",
  nested: "md3-surface-container-high", overlay: "md3-surface-container-highest", deepest: "md3-surface-container-lowest",
  hairline: "md3-outline-variant", ink: "text-primary", inkSecondary: "text-secondary", inkMuted: "text-muted",
  accent: "btn-primary-bg", accentHover: "btn-primary-hover", onAccent: "btn-primary-text", accentText: "accent-text",
  danger: "hsl-destructive",
  successBg: "surface-success-bg", successBorder: "surface-success-border", successText: "surface-success-text",
  warningBg: "surface-warning-bg", warningBorder: "surface-warning-border", warningText: "surface-warning-text",
  dangerBg: "surface-danger-bg", dangerBorder: "surface-danger-border", dangerText: "surface-danger-text",
  infoBg: "surface-info-bg", infoBorder: "surface-info-border", infoText: "surface-info-text",
  brandVibrant: "brand-vibrant", brandCool: "brand-cool", brandGlow: "brand-glow", brandPurple: "brand-purple",
};
const palette = (scope) => Object.fromEntries(Object.entries(ROLES).map(([k, t]) => [k, resolve(scope, t)]));
const lit = (o) => "{\n" + Object.entries(o).map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`).join("\n") + "\n  }";
const src = `// GENERATED by scripts/gen-palette.mjs from tokens.css and named-themes.css; do not edit.
// Brand's resolved colors for renderers that cannot read CSS variables: PDF, canvas,
// WebGL, email and the theme-color meta. Pages styled with CSS use the variables.

/** A theme's resolved roles: hex strings, or rgba() where the token is translucent. */
export interface BrandPalette {
${Object.keys(ROLES).map((k) => `  ${k}: string;`).join("\n")}
}

/** Resolved palettes for the canonical light and dark themes and the website named theme. */
export const palettes = {
  light: ${lit(palette(LIGHT))},
  dark: ${lit(palette(DARK))},
  websiteLight: ${lit(palette(WEBSITE_LIGHT))},
  websiteDark: ${lit(palette(WEBSITE_DARK))},
} as const satisfies Record<string, BrandPalette>;
`;
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== src) { console.error("src/palette.generated.ts is stale: run node scripts/gen-palette.mjs"); process.exit(1); }
} else { writeFileSync(OUT, src); console.log("wrote src/palette.generated.ts"); }
