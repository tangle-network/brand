/** Generate old consumer selectors from the canonical shared class owners. */
import { readFile,writeFile } from "node:fs/promises";
import { buttonVariants,inputVariants,tablePresentation,metricPresentation,cardPresentation } from "../dist/presentation.js";
const aliases={
 ".btn":buttonVariants({variant:null}),
 ".btn-primary":buttonVariants({variant:"default"}),
 ".btn-secondary":buttonVariants({variant:"secondary"}),
 ".btn-danger":buttonVariants({variant:"destructive"}),
 ".input":inputVariants(),
 ".card":[cardPresentation.root,cardPresentation.variants.default,cardPresentation.padding].join(" "),
 ".stat-card":[cardPresentation.root,cardPresentation.variants.default,metricPresentation.item].join(" "),
 ".table-header":tablePresentation.columnHeader,
 ".table-cell":tablePresentation.cell,
};
const css="/* Generated by scripts/generate-presentation-css.mjs from shared primitive recipes. Requires Tailwind + Brand theme. */\n@layer components {\n"+Object.entries(aliases).map(([selector,classes])=>`  ${selector} { @apply ${classes}; }`).join("\n")+"\n}\n";
const target=new URL("../src/styles/compat.css",import.meta.url);
if(process.argv.includes("--check")){
 if(await readFile(target,"utf8").catch(()=>"")!==css)throw Error("Regenerate UI compatibility recipes with node scripts/generate-presentation-css.mjs");
}else {await writeFile(target,css);console.log(target.pathname);}
